"""
Problem 9: Market making - quoting in a synthetic toxic-flow simulator
Clearance-safe: a Glosten-Milgrom-style simulator whose order flow is
generated entirely by code. No market data of any kind. All parameters
and the seed are declared below, before the run.

Registered question (PILOT.md, fixed before the run):
  In a Glosten-Milgrom-style synthetic simulator (informed /
  uninformed flow generated by code, no market data), what spread
  recovers zero expected loss to informed traders?
Registered verifier (fixed before the run):
  Simulation with known informed share (known by construction);
  break-even spread solved analytically and checked against
  simulation.

Conventions (fixed before the run):
  - Model. The asset's true value V is 90 or 110 with equal
    probability (prior mean 100, half-distance delta = 10). Traders
    arrive one at a time. A share mu of arrivals are informed: they
    know V, and buy when V = 110 and sell when V = 90. The remaining
    share 1 - mu are uninformed: they buy or sell with equal
    probability, independently of V.
  - Quotes. The market maker quotes a symmetric bid and ask around
    the prior mean: bid = 100 - h, ask = 100 + h, where h is the
    half-spread. The (full) spread is 2h. The market maker trades at
    the quote against every arrival.
  - Analytic solution. P(buy) = mu/2 + (1 - mu)/2 = 1/2, and
        E[V | buy] = mu * 110 + (1 - mu) * 100 = 100 + mu * delta.
    Expected profit on a buy is (100 + h) - E[V | buy] = h - mu*delta,
    and by symmetry the same on a sell, so the zero-expected-profit
    half-spread is h* = mu * delta and the break-even spread is
    s* = 2 * mu * delta.
  - Cases. The headline case is mu = 0.20 (break-even spread 4.00).
    A sweep mu in {0.05, 0.10, ..., 0.50} is run under the same rule.
  - Simulation. For each mu, N = 1,000,000 arrivals are generated
    from one random.Random stream seeded 20261104, mu values in
    increasing order. For each arrival the signed value term is
    g = -(V - 100) for a buy and g = (V - 100) for a sell, so that
    profit at half-spread h is exactly h + g per trade; the simulated
    break-even half-spread is h_hat = -mean(g); the simulated mean
    profit at the analytic h* is h* + mean(g). The verifier passes
    for a case if
        |h_hat - mu * delta| <= 3 * SE(mean g),
    with SE the standard error of the simulated mean of g.
"""
import json
import math
import random

DELTA = 10.0
N = 1_000_000
SEED = 20261104
MUS = [0.05 * i for i in range(1, 11)]
HEADLINE_MU = 0.20


def simulate(mu, rng):
    total_g = 0.0
    total_g2 = 0.0
    for _ in range(N):
        v = 110.0 if rng.random() < 0.5 else 90.0
        if rng.random() < mu:
            buy = v > 100.0  # informed: buy high value, sell low value
        else:
            buy = rng.random() < 0.5  # uninformed: coin flip
        g = -(v - 100.0) if buy else (v - 100.0)
        total_g += g
        total_g2 += g * g
    mean_g = total_g / N
    var_g = total_g2 / N - mean_g**2
    se = math.sqrt(var_g / N)
    return mean_g, se


def main():
    rng = random.Random(SEED)
    cases = []
    for mu in MUS:
        mean_g, se = simulate(mu, rng)
        h_hat = -mean_g
        h_star = mu * DELTA
        diff = abs(h_hat - h_star)
        passed = diff <= 3 * se
        cases.append(
            {
                "informed_share_mu": round(mu, 2),
                "analytic_breakeven_half_spread": h_star,
                "analytic_breakeven_spread": 2 * h_star,
                "simulated_breakeven_half_spread": h_hat,
                "simulated_breakeven_spread": 2 * h_hat,
                "standard_error_of_half_spread": se,
                "difference_in_standard_errors": diff / se if se else 0.0,
                "verifier_passed": passed,
            }
        )
        print(
            f"mu {mu:.2f}: analytic spread {2*h_star:5.2f}  simulated "
            f"{2*h_hat:7.4f}  (diff {diff/se:5.2f} SE)  pass {passed}"
        )
    headline = next(c for c in cases if c["informed_share_mu"] == HEADLINE_MU)
    out = {
        "problem": 9,
        "title": "Market making - break-even spread in a synthetic Glosten-Milgrom simulator",
        "verifier": "break-even half-spread solved analytically (h* = mu * delta) and checked against simulation with the informed share known by construction: 1,000,000 arrivals per mu, seed 20261104; pass requires |simulated - analytic| <= 3 standard errors of the simulated mean",
        "parameters": {"values": [90.0, 110.0], "delta": DELTA, "arrivals_per_mu": N},
        "headline_case": headline,
        "sweep": cases,
        "all_cases_passed": all(c["verifier_passed"] for c in cases),
        "verdict": (
            f"At the headline informed share mu = 0.20 the break-even "
            f"spread is 4.00 analytically and "
            f"{headline['simulated_breakeven_spread']:.3f} in simulation, "
            f"a difference of {headline['difference_in_standard_errors']:.2f} "
            f"standard errors. Across the sweep the break-even spread is "
            f"2 * mu * delta throughout, as the analytic solution states."
        ),
    }
    with open("result.json", "w") as f:
        json.dump(out, f, indent=2, sort_keys=True)


if __name__ == "__main__":
    main()
