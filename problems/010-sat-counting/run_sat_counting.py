"""
Problem 10: Exact counting for small SAT - DPLL scaling vs brute force
Clearance-safe: random synthetic 3-SAT instances generated by code.
No external data of any kind. All parameters and seeds are declared
below, before the run.

Registered question (PILOT.md, fixed before the run):
  The Oct 26 OpenAI/math addition claims a deterministic
  subexponential exact counter for fixed-width CNF formulas. On small
  random 3-SAT instances, how does a DPLL exact counter's runtime
  actually scale vs brute force?
Registered verifier (fixed before the run):
  Counts cross-checked by brute-force enumeration on every instance
  with <= 24 variables.

Conventions (fixed before the run):
  - Instances. Random 3-SAT: n variables, m = round(4.26 * n) clauses
    (the standard phase-transition clause density), each clause three
    distinct variables chosen uniformly without replacement, each
    literal's sign chosen uniformly. Sizes
    n in {8, 10, 12, 14, 16, 18, 20, 22, 24}; 20 instances per size.
    The generator seed for instance i at size index s is
    20261104 + 1000 * s + i, using one random.Random stream per
    instance. A literal is a nonzero integer: +j means variable j is
    true, -j means it is false; a clause is a tuple of three literals.
  - Brute force. Every one of the 2^n assignments is evaluated
    against every clause. The evaluation is bit-parallel (numpy
    boolean arrays over the full assignment space), but it is a
    complete enumeration: no assignment is skipped, pruned, or
    sampled. A clause counts as satisfied if at least one of its
    literals is true; the count is the number of assignments
    satisfying all clauses.
  - DPLL counter. A plain recursive exact model counter: unit
    propagation to a fixed point (an empty clause contributes 0; an
    empty formula contributes 2^(number of unassigned variables)),
    then branching on the first literal of the first remaining
    clause, summing the counts of both branches. No clause learning,
    no component caching, no memoisation.
  - Timing. Wall-clock seconds per instance per method, measured with
    time.perf_counter around the counting call only (instance
    generation excluded). The median across the 20 instances at each
    size is reported. Scaling is summarised by the slope of a
    least-squares fit of log(median time) against n, reported as an
    effective per-variable multiplicative factor exp(slope); brute
    force is expected to give a factor near 2.
  - Verdict rule. The verifier passes if the DPLL count equals the
    brute-force count on every one of the 180 instances. The runtime
    figures are reported as measurement (on this machine, at these
    sizes), not as a proven asymptotic claim.
"""
import json
import math
import random
import sys
import time

import numpy as np

sys.setrecursionlimit(100000)

SIZES = [8, 10, 12, 14, 16, 18, 20, 22, 24]
INSTANCES = 20
RATIO = 4.26
SEED_BASE = 20261104


def gen_instance(n, seed):
    rng = random.Random(seed)
    m = round(RATIO * n)
    clauses = []
    for _ in range(m):
        vs = rng.sample(range(1, n + 1), 3)
        clauses.append(tuple(v if rng.random() < 0.5 else -v for v in vs))
    return clauses


def brute_force_count(clauses, n):
    total = 1 << n
    idx = np.arange(total, dtype=np.uint64)
    sat = np.ones(total, dtype=bool)
    var_true = {}
    for v in range(1, n + 1):
        var_true[v] = ((idx >> (v - 1)) & 1) == 1
    for clause in clauses:
        c_sat = np.zeros(total, dtype=bool)
        for lit in clause:
            if lit > 0:
                c_sat |= var_true[lit]
            else:
                c_sat |= ~var_true[-lit]
        sat &= c_sat
        if not sat.any():
            break
    return int(sat.sum())


def simplify(clauses, lit):
    out = []
    for c in clauses:
        if lit in c:
            continue
        if -lit in c:
            c = tuple(x for x in c if x != -lit)
        out.append(c)
    return out


def dpll_count(clauses, assigned, n):
    # Unit propagation to a fixed point.
    while True:
        if any(len(c) == 0 for c in clauses):
            return 0
        unit = None
        for c in clauses:
            if len(c) == 1:
                unit = c[0]
                break
        if unit is None:
            break
        assigned = assigned | {abs(unit)}
        clauses = simplify(clauses, unit)
    if not clauses:
        return 1 << (n - len(assigned))
    var = abs(clauses[0][0])
    assigned2 = assigned | {var}
    return (
        dpll_count(simplify(clauses, var), assigned2, n)
        + dpll_count(simplify(clauses, -var), assigned2, n)
    )


def main():
    per_size = []
    all_agree = True
    total_instances = 0
    for s, n in enumerate(SIZES):
        bf_times, dp_times = [], []
        counts = []
        agree = True
        for i in range(INSTANCES):
            clauses = gen_instance(n, SEED_BASE + 1000 * s + i)
            t0 = time.perf_counter()
            c_bf = brute_force_count(clauses, n)
            t1 = time.perf_counter()
            c_dp = dpll_count([tuple(c) for c in clauses], frozenset(), n)
            t2 = time.perf_counter()
            bf_times.append(t1 - t0)
            dp_times.append(t2 - t1)
            counts.append(c_bf)
            total_instances += 1
            if c_bf != c_dp:
                agree = False
                print(f"MISMATCH n={n} instance={i}: brute {c_bf} vs dpll {c_dp}")
        all_agree &= agree
        bf_med = float(np.median(bf_times))
        dp_med = float(np.median(dp_times))
        per_size.append(
            {
                "n": n,
                "clauses_m": round(RATIO * n),
                "instances": INSTANCES,
                "counts_agree": agree,
                "brute_force_median_seconds": bf_med,
                "dpll_median_seconds": dp_med,
                "median_time_ratio_dpll_over_brute": dp_med / bf_med if bf_med else None,
                "model_counts": counts,
            }
        )
        print(
            f"n={n:3d} m={round(RATIO*n):3d} agree={agree} "
            f"brute median {bf_med:9.4f}s  dpll median {dp_med:9.4f}s  "
            f"ratio {dp_med / bf_med:8.3f}"
        )

    def eff_factor(meds):
        xs = np.array(SIZES, dtype=float)
        ys = np.log(np.array(meds))
        slope = float(np.polyfit(xs, ys, 1)[0])
        return slope, math.exp(slope)

    bf_slope, bf_factor = eff_factor([p["brute_force_median_seconds"] for p in per_size])
    dp_slope, dp_factor = eff_factor([p["dpll_median_seconds"] for p in per_size])

    out = {
        "problem": 10,
        "title": "Exact counting for small SAT - DPLL counter scaling vs brute force",
        "verifier": "DPLL exact counts cross-checked by complete brute-force enumeration (bit-parallel evaluation of all 2^n assignments) on every instance; n <= 24; verifier passes only if all counts agree",
        "parameters": {
            "sizes_n": SIZES, "instances_per_size": INSTANCES,
            "clause_ratio": RATIO, "seed_base": SEED_BASE,
        },
        "total_instances": total_instances,
        "all_counts_agree": all_agree,
        "per_size": per_size,
        "scaling_fit": {
            "brute_force_log_slope_per_variable": bf_slope,
            "brute_force_effective_factor_per_variable": bf_factor,
            "dpll_log_slope_per_variable": dp_slope,
            "dpll_effective_factor_per_variable": dp_factor,
        },
        "verdict": (
            f"DPLL and brute-force counts agree on all {total_instances} "
            f"instances. Over n = 8..24 the median brute-force time grows "
            f"by an effective factor of {bf_factor:.2f} per added variable "
            f"and the median DPLL time by {dp_factor:.2f}; at n = 24 the "
            f"median DPLL time is {per_size[-1]['dpll_median_seconds']:.3f}s "
            f"against {per_size[-1]['brute_force_median_seconds']:.3f}s for "
            f"brute force. These are measurements on small instances, not "
            f"an asymptotic claim."
        ),
    }
    with open("result.json", "w") as f:
        json.dump(out, f, indent=2, sort_keys=True)
    print("ALL AGREE:", all_agree)


if __name__ == "__main__":
    main()
